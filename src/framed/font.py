GLYPHS: dict[str, list[list[bool]]] = {
    ch: [[c == "#" for c in row] for row in rows] for ch, rows in _RAW.items()
}
_BLANK = GLYPHS[" "]


def glyph(ch: str) -> list[list[bool]]:
    return GLYPHS.get(ch.upper(), _BLANK)


def text_width(text: str, spacing: int = 1) -> int:
    if not text:
        return 0
    return len(text) * GLYPH_W + (len(text) - 1) * spacing


def draw_text(
    image: Image.Image,
    text: str,
    x: int,
    y: int,
    color: tuple[int, int, int],
    spacing: int = 1,
    scale: int = 1,
) -> None:
    px = image.load()
    w, h = image.size
    cx = x
    for ch in text:
        for row, cells in enumerate(glyph(ch)):
            for col, lit in enumerate(cells):
                if not lit:
                    continue
                for dy in range(scale):
                    for dx in range(scale):
                        px_x = cx + col * scale + dx
                        px_y = y + row * scale + dy
                        if 0 <= px_x < w and 0 <= px_y < h:
                            px[px_x, px_y] = color
        cx += (GLYPH_W + spacing) * scale


def fit_text(text: str, width: int) -> tuple[str, int]:
    """Return (text, spacing) that fits in ``width`` pixels, dropping spacing then characters."""
    if text_width(text, 1) <= width:
        return text, 1
    if text_width(text, 0) <= width:
        return text, 0
    return text[: max(1, width // GLYPH_W)], 0


def draw_centered(
    image: Image.Image, text: str, y: int, color: tuple[int, int, int], scale: int = 1
) -> None:
    width = image.size[0]
    if scale > 1:
        text, spacing = fit_text(text, width // scale)
        tw = text_width(text, spacing) * scale
    else:
        text, spacing = fit_text(text, width)
        tw = text_width(text, spacing)
    draw_text(image, text, (width - tw) // 2, y, color, spacing, scale)
